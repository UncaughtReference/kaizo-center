create table public.reviews (
    id bigint generated by default as identity primary key,
    hack_name text not null,
    hack_kind text not null check (hack_kind in ('hack', 'coop')),
    user_id uuid not null references public.profiles(user_id) on delete cascade,
    body text not null check (char_length(trim(body)) between 1 and 5000),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (hack_name, hack_kind, user_id)
);

create index reviews_hack_lookup_idx on public.reviews (hack_kind, hack_name, created_at desc);
alter table public.reviews enable row level security;
revoke all on public.reviews from anon, authenticated;

create or replace function public.can_review_hack(p_user_id uuid, p_hack_name text, p_hack_kind text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_role smallint;
    v_star_total integer;
    v_offset integer := 0;
    v_page_count integer;
    v_progress record;
begin
    if auth.uid() is null or p_user_id <> (select auth.uid()) or p_hack_kind not in ('hack', 'coop') then
        return false;
    end if;
    select profile.role into v_role from public.profiles profile where profile.user_id = p_user_id;
    if not found or v_role = 3 then return false; end if;

    if p_hack_kind = 'coop' then
        select hack.star_count into v_star_total from public.coop_hacks hack where hack.name = p_hack_name;
    else
        select hack.star_count into v_star_total from public.hacks hack where hack.name = p_hack_name;
    end if;
    if not found or v_star_total is null then return false; end if;

    loop
        v_page_count := 0;
        for v_progress in select * from public.get_my_progress(v_offset, 1000) loop
            v_page_count := v_page_count + 1;
            if v_progress.hack_name = p_hack_name
                and v_progress.hack_kind = p_hack_kind
                and (not coalesce(v_progress.is_helper, false) or p_hack_kind = 'coop')
                and v_progress.star_count::numeric >= v_star_total::numeric * 0.5 then
                return true;
            end if;
        end loop;
        exit when v_page_count < 1000;
        v_offset := v_offset + 1000;
    end loop;
    return false;
end
$$;

revoke all on function public.can_review_hack(uuid, text, text) from public, anon, authenticated;

create or replace function public.get_hack_reviews(p_hack_name text, p_hack_kind text)
returns table (
    id bigint,
    user_id uuid,
    username text,
    display_name text,
    body text,
    created_at timestamptz,
    updated_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
    select review.id, review.user_id, profile.username, profile.display_name,
           review.body, review.created_at, review.updated_at
    from public.reviews review
    join public.profiles profile on profile.user_id = review.user_id
    where review.hack_name = p_hack_name
      and review.hack_kind = p_hack_kind
    order by review.created_at desc, review.id desc
$$;

revoke all on function public.get_hack_reviews(text, text) from public;
grant execute on function public.get_hack_reviews(text, text) to anon, authenticated;

create or replace function public.create_hack_review(p_hack_name text, p_hack_kind text, p_body text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_id bigint;
begin
    if auth.uid() is null then
        raise exception 'Sign in to post a review.';
    end if;
    if p_hack_kind not in ('hack', 'coop') then
        raise exception 'Invalid hack type.';
    end if;
    if char_length(trim(coalesce(p_body, ''))) not between 1 and 5000 then
        raise exception 'Reviews must contain between 1 and 5000 characters.';
    end if;
    if not public.can_review_hack((select auth.uid()), p_hack_name, p_hack_kind) then
        raise exception 'You need a progress submission with at least half the stars to review this hack.';
    end if;

    insert into public.reviews (hack_name, hack_kind, user_id, body)
    values (p_hack_name, p_hack_kind, (select auth.uid()), trim(p_body))
    returning id into v_id;
    return v_id;
end
$$;

create or replace function public.update_hack_review(p_review_id bigint, p_body text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_review public.reviews%rowtype;
begin
    if auth.uid() is null then
        raise exception 'Sign in to edit a review.';
    end if;
    if char_length(trim(coalesce(p_body, ''))) not between 1 and 5000 then
        raise exception 'Reviews must contain between 1 and 5000 characters.';
    end if;
    select * into v_review from public.reviews where id = p_review_id;
    if not found or v_review.user_id <> (select auth.uid()) then
        raise exception 'Only the original poster can edit this review.';
    end if;
    update public.reviews
    set body = trim(p_body), updated_at = now()
    where id = p_review_id;
    return true;
end
$$;

create or replace function public.delete_hack_review(p_review_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_review public.reviews%rowtype;
begin
    if auth.uid() is null then
        raise exception 'Sign in to delete a review.';
    end if;
    select * into v_review from public.reviews where id = p_review_id;
    if not found then
        return false;
    end if;
    if v_review.user_id <> (select auth.uid()) and coalesce(public.current_profile_role(), 0) <> 2 then
        raise exception 'Only the original poster or a moderator can delete this review.';
    end if;
    delete from public.reviews where id = p_review_id;
    return true;
end
$$;

revoke all on function public.create_hack_review(text, text, text) from public, anon;
revoke all on function public.update_hack_review(bigint, text) from public, anon;
revoke all on function public.delete_hack_review(bigint) from public, anon;
grant execute on function public.create_hack_review(text, text, text) to authenticated;
grant execute on function public.update_hack_review(bigint, text) to authenticated;
grant execute on function public.delete_hack_review(bigint) to authenticated;
